/**
 * Synchronize the 100 FirstCry curated catalog directly into Supabase database
 */
export async function syncFirstCryCatalogToSupabase(
  onProgress?: (current: number, total: number, message: string) => void,
): Promise<{ success: boolean; count: number; error?: string }> {
  try {
    // 1. Sync Categories
    onProgress?.(0, FIRSTCRY_100_PRODUCTS.length, "Syncing categories...");
    for (const cat of FIRSTCRY_CATEGORIES) {
      await supabase.from("categories").upsert(
        {
          slug: cat.slug,
          name: cat.name,
          tagline: cat.tagline,
          sort_order: cat.sort_order,
        },
        { onConflict: "slug" },
      );
    }

    // 2. Batch sync products
    let synced = 0;
    const batchSize = 10;

    for (let i = 0; i < FIRSTCRY_100_PRODUCTS.length; i += batchSize) {
      const batch = FIRSTCRY_100_PRODUCTS.slice(i, i + batchSize);

      for (const item of batch) {
        // Upsert product
        const { data: productData, error: prodErr } = await supabase
          .from("products")
          .upsert(
            {
              slug: item.slug,
              name: item.name,
              brand: item.brand,
              category: item.category,
              price: item.price,
              mrp: item.mrp,
              rating: item.rating,
              reviews: item.reviews,
              age_group: item.ageGroup,
              description: item.description,
              highlights: item.highlights,
              is_featured: item.isFeatured,
              is_active: item.isActive,
              stock: item.stock,
              low_stock_at: item.lowStockAt,
              sku: item.sku,
              barcode: item.barcode,
              sort_order: item.sortOrder,
            },
            { onConflict: "slug" },
          )
          .select("id")
          .single();

        if (prodErr) {
          console.warn(`Product upsert error for ${item.slug}:`, prodErr);
          continue;
        }

        const productId = productData?.id;
        if (productId) {
          // Upsert product cost
          await supabase.from("product_costs").upsert(
            {
              product_id: productId,
              buying_price: item.buyingPrice,
            },
            { onConflict: "product_id" },
          );

          // Cleanly replace product images with the item's distinct image
          await supabase.from("product_images").delete().eq("product_id", productId);
          await supabase.from("product_images").insert({
            product_id: productId,
            public_url: item.imageUrl,
            storage_path: "",
            alt_text: item.name,
            is_primary: true,
            sort_order: 0,
          });
        }

        synced++;
      }

      onProgress?.(
        Math.min(i + batchSize, FIRSTCRY_100_PRODUCTS.length),
        FIRSTCRY_100_PRODUCTS.length,
        `Synced ${Math.min(i + batchSize, FIRSTCRY_100_PRODUCTS.length)} of ${FIRSTCRY_100_PRODUCTS.length} products...`,
      );
    }

    return { success: true, count: synced };
  } catch (err: unknown) {
    console.error("Error syncing FirstCry catalog:", err);
    return { success: false, count: 0, error: (err as Error)?.message || String(err) };
  }
}
